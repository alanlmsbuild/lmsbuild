-- Checks for sql/crm_02_record_view_tags.sql: run these one at a time, as
-- ACCOUNTADMIN, straight after it. (npm run check:grants and
-- npm run check:tags -- --crm check the same things as CRM_APP_USER.)

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE capture_wh;

-- 1. The view log is there and empty. Expected: 1 row, N 0.
SELECT 'RECORD_VIEW' AS T, COUNT(*) AS N FROM CRM_DB.CRM.RECORD_VIEW;

-- 2. CRM_APP_ROLE may only add to it. Expected: 1 row, INSERT.
SHOW GRANTS ON TABLE CRM_DB.CRM.RECORD_VIEW
  ->> SELECT "privilege", "grantee_name" FROM $1 WHERE "grantee_name" = 'CRM_APP_ROLE';

-- 3. USAGE on the tags' schema, and no APPLY on any tag. Expected: 1 row,
--    USAGE on SHARED_DB.GOVERNANCE.
SHOW GRANTS TO ROLE CRM_APP_ROLE
  ->> SELECT "privilege", "granted_on", "name" FROM $1
      WHERE "name" LIKE 'SHARED_DB.GOVERNANCE%' OR "privilege" = 'APPLY';

-- 4. The tags. Expected: LEAD minor (table); GIVENNAMES, FAMILYNAME, EMAIL,
--    MOBILE, DATEOFBIRTH, POSTCODE personal (LEAD columns); TOADDRESS and
--    BODY personal. 9 rows.
SELECT OBJECT_NAME, COLUMN_NAME, DOMAIN, TAG_VALUE
FROM TABLE(CRM_DB.INFORMATION_SCHEMA.TAG_REFERENCES('CRM_DB.CRM.LEAD', 'table'))
WHERE TAG_NAME = 'SENSITIVITY'
UNION ALL
SELECT OBJECT_NAME, COLUMN_NAME, DOMAIN, TAG_VALUE
FROM TABLE(CRM_DB.INFORMATION_SCHEMA.TAG_REFERENCES_ALL_COLUMNS('CRM_DB.CRM.LEAD', 'table'))
WHERE TAG_NAME = 'SENSITIVITY' AND LEVEL = 'COLUMN'
UNION ALL
SELECT OBJECT_NAME, COLUMN_NAME, DOMAIN, TAG_VALUE
FROM TABLE(CRM_DB.INFORMATION_SCHEMA.TAG_REFERENCES_ALL_COLUMNS('CRM_DB.CRM.EMAIL_MESSAGE', 'table'))
WHERE TAG_NAME = 'SENSITIVITY' AND LEVEL = 'COLUMN'
UNION ALL
SELECT OBJECT_NAME, COLUMN_NAME, DOMAIN, TAG_VALUE
FROM TABLE(CRM_DB.INFORMATION_SCHEMA.TAG_REFERENCES_ALL_COLUMNS('CRM_DB.CRM.ACTIVITY', 'table'))
WHERE TAG_NAME = 'SENSITIVITY' AND LEVEL = 'COLUMN';

-- 5. Later, after the person record has been used: who opened which
--    records. Test views have ISTESTDATA TRUE.
SELECT VIEWEDBY, ORGANISATIONID, RECORDTYPE, COUNT(*) AS VIEWS, MAX(VIEWEDAT) AS LAST_VIEW, COUNT_IF(NOT ISTESTDATA) AS REAL_VIEWS
FROM CRM_DB.CRM.RECORD_VIEW
GROUP BY 1, 2, 3
ORDER BY 1;

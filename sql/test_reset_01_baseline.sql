-- 1. What the snapshot holds. Expected, if nothing has been changed since
--    28 September 2026: LEARNER 116, LEARNING_DELIVERY 288,
--    PRIOR_ATTAINMENT 116, LLDD_HEALTH_PROBLEM 25, LEARNER_FAM 0,
--    EMPLOYMENT_STATUS 116, EMPLOYMENT_STATUS_MONITORING 232,
--    LEARNING_DELIVERY_FAM 9, APP_FIN_RECORD 232, HOURS_RECORD 175,
--    OFFICER_ASSIGNMENT 235, LEARNER_EMPLOYER 97. And 0 in NOT_TEST.
SELECT 'LEARNER' AS TABLE_NAME, COUNT(*) AS ROWS_, COUNT_IF(NOT ISTESTDATA) AS NOT_TEST FROM CAPTURE_DB.TEST_BASELINE.LEARNER
UNION ALL SELECT 'LEARNING_DELIVERY', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CAPTURE_DB.TEST_BASELINE.LEARNING_DELIVERY
UNION ALL SELECT 'PRIOR_ATTAINMENT', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CAPTURE_DB.TEST_BASELINE.PRIOR_ATTAINMENT
UNION ALL SELECT 'LLDD_HEALTH_PROBLEM', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CAPTURE_DB.TEST_BASELINE.LLDD_HEALTH_PROBLEM
UNION ALL SELECT 'LEARNER_FAM', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CAPTURE_DB.TEST_BASELINE.LEARNER_FAM
UNION ALL SELECT 'EMPLOYMENT_STATUS', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CAPTURE_DB.TEST_BASELINE.EMPLOYMENT_STATUS
UNION ALL SELECT 'EMPLOYMENT_STATUS_MONITORING', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CAPTURE_DB.TEST_BASELINE.EMPLOYMENT_STATUS_MONITORING
UNION ALL SELECT 'LEARNING_DELIVERY_FAM', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CAPTURE_DB.TEST_BASELINE.LEARNING_DELIVERY_FAM
UNION ALL SELECT 'APP_FIN_RECORD', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CAPTURE_DB.TEST_BASELINE.APP_FIN_RECORD
UNION ALL SELECT 'HOURS_RECORD', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CAPTURE_DB.TEST_BASELINE.HOURS_RECORD
UNION ALL SELECT 'OFFICER_ASSIGNMENT', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CAPTURE_DB.TEST_BASELINE.OFFICER_ASSIGNMENT
UNION ALL SELECT 'LEARNER_EMPLOYER', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CAPTURE_DB.TEST_BASELINE.LEARNER_EMPLOYER;

-- 2. The app's role can't see the snapshot. Expected: no rows.
SHOW GRANTS ON SCHEMA CAPTURE_DB.TEST_BASELINE;
SELECT * FROM TABLE(RESULT_SCAN(LAST_QUERY_ID())) WHERE "grantee_name" = 'ILR_APP_ROLE';

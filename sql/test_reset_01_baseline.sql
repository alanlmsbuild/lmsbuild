-- Resetting the test learners, file 1 of 2: TEST DATA ONLY. Takes a
-- snapshot of every test learner (ISTESTDATA = TRUE) and the records the
-- learner page can change, so sql/test_reset_02_reset.sql can put them back
-- after testing, with the QAR mix as it was.
--
-- Run by hand as ACCOUNTADMIN in a Snowflake worksheet, once, AFTER
-- sql/ilr_04_capture.sql (so the snapshot has the new columns) and before
-- testing the capture screens. Safe to run twice: a snapshot table that
-- already exists is left as it is, so running it again never overwrites the
-- snapshot with edited data. To take a new snapshot, drop the schema first
-- (DROP SCHEMA CAPTURE_DB.TEST_BASELINE) and run this again.
--
-- The snapshot lives in its own schema, CAPTURE_DB.TEST_BASELINE, owned by
-- ACCOUNTADMIN. The app's role (ILR_APP_ROLE) is given no access to it.
-- Only test rows are copied: each table is filtered on ISTESTDATA = TRUE,
-- and tables keyed by learner also on the learner being a test learner.
--
-- What's in it: ILR.LEARNER, LEARNING_DELIVERY, the 8 ILR record tables,
-- OFFICER_ASSIGNMENT and LEARNER_EMPLOYER, as they are when this is run.
-- On 28 September 2026 that was 116 test learners (all in ORG-T001 and
-- ORG-T002) and no real rows on any of them.
--
-- If a later SQL file adds a column to one of these tables, it must add it
-- to the snapshot table too, or the reset can't copy the rows back (it
-- stops and changes nothing).

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE capture_wh;

CREATE SCHEMA IF NOT EXISTS CAPTURE_DB.TEST_BASELINE
  COMMENT = 'TEST DATA ONLY: a snapshot of the test learners, for sql/test_reset_02_reset.sql. No access for the app.';

CREATE TABLE IF NOT EXISTS CAPTURE_DB.TEST_BASELINE.LEARNER AS
  SELECT * FROM CAPTURE_DB.ILR.LEARNER WHERE ISTESTDATA = TRUE;

CREATE TABLE IF NOT EXISTS CAPTURE_DB.TEST_BASELINE.LEARNING_DELIVERY AS
  SELECT * FROM CAPTURE_DB.ILR.LEARNING_DELIVERY
  WHERE ISTESTDATA = TRUE AND LEARNREFNUMBER IN (SELECT LEARNREFNUMBER FROM CAPTURE_DB.ILR.LEARNER WHERE ISTESTDATA = TRUE);

CREATE TABLE IF NOT EXISTS CAPTURE_DB.TEST_BASELINE.PRIOR_ATTAINMENT AS
  SELECT * FROM CAPTURE_DB.ILR.PRIOR_ATTAINMENT
  WHERE ISTESTDATA = TRUE AND LEARNREFNUMBER IN (SELECT LEARNREFNUMBER FROM CAPTURE_DB.ILR.LEARNER WHERE ISTESTDATA = TRUE);

CREATE TABLE IF NOT EXISTS CAPTURE_DB.TEST_BASELINE.LLDD_HEALTH_PROBLEM AS
  SELECT * FROM CAPTURE_DB.ILR.LLDD_HEALTH_PROBLEM
  WHERE ISTESTDATA = TRUE AND LEARNREFNUMBER IN (SELECT LEARNREFNUMBER FROM CAPTURE_DB.ILR.LEARNER WHERE ISTESTDATA = TRUE);

CREATE TABLE IF NOT EXISTS CAPTURE_DB.TEST_BASELINE.LEARNER_FAM AS
  SELECT * FROM CAPTURE_DB.ILR.LEARNER_FAM
  WHERE ISTESTDATA = TRUE AND LEARNREFNUMBER IN (SELECT LEARNREFNUMBER FROM CAPTURE_DB.ILR.LEARNER WHERE ISTESTDATA = TRUE);

CREATE TABLE IF NOT EXISTS CAPTURE_DB.TEST_BASELINE.EMPLOYMENT_STATUS AS
  SELECT * FROM CAPTURE_DB.ILR.EMPLOYMENT_STATUS
  WHERE ISTESTDATA = TRUE AND LEARNREFNUMBER IN (SELECT LEARNREFNUMBER FROM CAPTURE_DB.ILR.LEARNER WHERE ISTESTDATA = TRUE);

CREATE TABLE IF NOT EXISTS CAPTURE_DB.TEST_BASELINE.EMPLOYMENT_STATUS_MONITORING AS
  SELECT * FROM CAPTURE_DB.ILR.EMPLOYMENT_STATUS_MONITORING
  WHERE ISTESTDATA = TRUE AND LEARNREFNUMBER IN (SELECT LEARNREFNUMBER FROM CAPTURE_DB.ILR.LEARNER WHERE ISTESTDATA = TRUE);

CREATE TABLE IF NOT EXISTS CAPTURE_DB.TEST_BASELINE.LEARNING_DELIVERY_FAM AS
  SELECT * FROM CAPTURE_DB.ILR.LEARNING_DELIVERY_FAM
  WHERE ISTESTDATA = TRUE AND LEARNREFNUMBER IN (SELECT LEARNREFNUMBER FROM CAPTURE_DB.ILR.LEARNER WHERE ISTESTDATA = TRUE);

CREATE TABLE IF NOT EXISTS CAPTURE_DB.TEST_BASELINE.APP_FIN_RECORD AS
  SELECT * FROM CAPTURE_DB.ILR.APP_FIN_RECORD

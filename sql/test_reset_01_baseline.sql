CREATE TABLE IF NOT EXISTS CAPTURE_DB.TEST_BASELINE.HOURS_RECORD AS
  SELECT * FROM CAPTURE_DB.ILR.HOURS_RECORD
  WHERE ISTESTDATA = TRUE AND LEARNREFNUMBER IN (SELECT LEARNREFNUMBER FROM CAPTURE_DB.ILR.LEARNER WHERE ISTESTDATA = TRUE);

CREATE TABLE IF NOT EXISTS CAPTURE_DB.TEST_BASELINE.OFFICER_ASSIGNMENT AS
  SELECT * FROM CAPTURE_DB.ILR.OFFICER_ASSIGNMENT
  WHERE ISTESTDATA = TRUE AND LEARNREFNUMBER IN (SELECT LEARNREFNUMBER FROM CAPTURE_DB.ILR.LEARNER WHERE ISTESTDATA = TRUE);

CREATE TABLE IF NOT EXISTS CAPTURE_DB.TEST_BASELINE.LEARNER_EMPLOYER AS
  SELECT * FROM CAPTURE_DB.ILR.LEARNER_EMPLOYER
  WHERE ISTESTDATA = TRUE AND LEARNREFNUMBER IN (SELECT LEARNREFNUMBER FROM CAPTURE_DB.ILR.LEARNER WHERE ISTESTDATA = TRUE);


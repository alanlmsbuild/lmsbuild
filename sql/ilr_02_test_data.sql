         DATEDIFF(day, ld.LEARNSTARTDATE, ld.LEARNACTENDDATE) AS ACTUAL_DAYS
  FROM CAPTURE_DB.ILR.LEARNING_DELIVERY ld
  JOIN CAPTURE_DB.ILR.LEARNER l ON l.LEARNREFNUMBER = ld.LEARNREFNUMBER
  WHERE ld.AIMTYPE = 1 AND ld.PROGTYPE IN (2, 3, 10, 20, 21, 22, 23, 25)
)
SELECT ORGANISATIONID, HYBRID_END_YEAR || ' to ' || (HYBRID_END_YEAR + 1) AS ACADEMIC_YEAR,
       COUNT(*) AS LEAVERS, COUNT_IF(COMPSTATUS = 2) AS COMPLETERS, COUNT_IF(OUTCOME = 1) AS ACHIEVERS
FROM aims
WHERE HYBRID_END_YEAR IN (2024, 2025) AND COMPSTATUS IN (2, 3)
  AND NOT (COMPSTATUS = 3 AND COALESCE(OUTCOME, 0) <> 1
           AND ((PLANNED_DAYS >= 168 AND ACTUAL_DAYS < 42) OR (PLANNED_DAYS BETWEEN 14 AND 167 AND ACTUAL_DAYS < 14)))
  AND COALESCE(WITHDRAWREASON, 0) <> 7
GROUP BY 1, 2
ORDER BY 1, 2;

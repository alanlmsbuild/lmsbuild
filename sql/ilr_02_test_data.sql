-- ILR return, file 2 of 2: TEST DATA ONLY. Corrects Warren's test learners and
-- adds the ILR records they need, so a 2026 to 2027 ILR file made from them
-- passes the schema and every validation rule Warren can check itself.
--
-- Run by hand as ACCOUNTADMIN in a Snowflake worksheet, after
-- ilr_01_tables.sql. Safe to run twice: new records are only added if they
-- aren't there already (MERGE ... WHEN NOT MATCHED), and each correction
-- only changes a value that still has its old seeded value, so changes made
-- in the app since are never overwritten. Every row it adds has ISTESTDATA =
-- TRUE, and every row it changes already has.
--
-- Generated from a script with a fixed seed, from the data as it was on
-- 28 September 2026.
--
-- Corrections
--   UKPRN   ORG-T001 99999999 (the UKPRN in DfE's sample ILR file) and
--           ORG-T002 99999998. Neither is on the UK Register of Learning
--           Providers (searched 28 September 2026), so no real provider's
--           UKPRN is used.
--   Names   The ILR schema doesn't allow digits in a family name, so
--           "TestlearnerNN" becomes "Testlearner-" and the number in words,
--           e.g. Testlearner17 -> Testlearner-OneSeven. Login display names
--           follow. Emails and learner references don't change.
--   NI      Every test learner gets a ZZ NI number (ZZ000017D). The QQ ones
--           failed rule NINumber_01 (Q isn't allowed first). ZZ passes the
--           format and HMRC never issues it. TESTL0013's real-looking NI
--           number, address and phone number are replaced too.
--   Address Address line 1 is required (AddLine1_03): "17 Test Street",
--           "Testville".
--   TESTL0015  Prior postcode ZZ2 2BC -> ZZ2 2BD (C isn't allowed in the
--           last part of a postcode, PostcodePrior_02).
--   Ages    8 learners started before they were old enough (DateOfBirth_48:
--           not until after the last Friday in June of the academic year
--           they turn 16). Their dates of birth move back one year.
--   Breaks  The 4 programme aims on a break in learning get outcome 3,
--           as an aim with an actual end date must have an outcome
--           (Outcome_12) and a break can't be 1 or 8 (CompStatus_06).
--   Failed end-point assessments. For apprenticeship standards, completion
--           status 2 means the training AND the end-point assessment are
--           done, so it always has an achievement date (AchDate_12), and the
--           achievement date records the end of the assessment period,
--           whatever the result. A failed assessment is:
--             CompStatus 2, Outcome 3 (no achievement),
--             LearnActEndDate = the last day of learning (before the
--             assessment), AchDate = the day the assessment ended.
--           (Provider support manual, "Recording apprenticeship
--           programmes", the ILR 2026 to 2027 fields CompStatus, Outcome,
--           AchDate, and rules AchDate_12, CompStatus_07, Outcome_04 - which
--           doesn't apply to standards.) While waiting for the assessment
--           the aim is CompStatus 1, Outcome 8, with the actual end date.
--           The 7 seeded "completed, not achieved" learners had no
--           achievement date. They get the date their assessment ended,
--           6 to 10 weeks after their last day of learning and in the same
--           academic year, so the QAR is unchanged (check 9).
--   EPAOrgID Every programme aim gets a test assessment organisation ID
--           (EPA9991, EPA9992, EPA9993 for ST0259, ST0005, ST0072). They are
--           not on the register, like the test ULNs aren't on the Learner
--           Register: only DfE's reference-data checks would reject them.
--
-- New records (all ISTESTDATA)
--   Component aims (AIMTYPE 3): every programme aim gets its standard's own
--     aim from LARS (Z0001849 for 111, Z0001831 for 119, Z0001875 for 122) at AIMSEQNUMBER 2,
--     closed the same way as the programme (R_31, R_89, R_90). Open
--     programmes whose prior attainment is below a full level 2 also get
--     Functional Skills English (60350544) and maths (6035060X), Level 2,
--     NCFE, at 3 and 4: 28 learners.
--   Prior attainment: one per learner, dated the programme start (R_131).
--   LLDD categories: 1 or 2 for each learner with LLDDHEALTHPROB = 1, one
--     marked primary (LLDDHealthProb_06, PrimaryLLDD_01), and learning
--     support funding (LSF) on their open programmes.
--   Employment status: employed (10) before the start date, with the
--     employer's reference from Warren as the employer ID, or 999999999
--     (not on the Employer Data Service) for learners without a Warren
--     employer, an employment intensity (EII) and a length of employment
--     (LOE) that matches the date (EmpStat_09, EmpId_10, ESMType_02,
--     ESMType_09). Learners with a Warren employer get a test agreement ID.
--   Prices: TNP 1 (training) and TNP 2 (assessment) from the start date,
--     within the LARS funding band cap: 111 1700+300, 119 1700+300, 122 2550+450
--     (AFinType_12, AFinType_13, R_100, EPAOrgID_02).
--   Off-the-job hours: planned (HRS 1) for every programme, about 6 hours a
--     week and at least 278 (starts to July 2025) or 187 (from August 2025),
--     actual (HRS 3) for the 59 completed or withdrawn (HRSType_01, 08, 09).
--
-- The export (step 2) adds the source of funding (SOF 105) to every aim and
-- the contract type (ACT 1, from the start date to the achievement date or
-- actual end date) to programme and English and maths aims, so those
-- aren't stored.


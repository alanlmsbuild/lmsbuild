--   Every table with an ISTESTDATA column: its test rows (ISTESTDATA =
--   TRUE) are deleted and the snapshot's put back. Nothing else decides
--   what is test data. The tables: in CAPTURE_DB.ILR, LEARNER,
--   LEARNING_DELIVERY, the 8 ILR record tables, OFFICER_ASSIGNMENT,
--   LEARNER_EMPLOYER, EMPLOYER, EMPLOYER_SITE, EMPLOYER_CONTACT,
--   EMPLOYER_VACANCY and ONBOARDING; in SHARED_DB.ACCESS, APP_USER,
--   USER_ROLE and APP_USER_SITE (so sign-ins made while testing, such as
--   flow F6's CANDIDATE sign-ins, go); and every table in CRM_DB (BRONZE
--   and CRM).
--   ILR.PROGRESS_REVIEW and the Burrow tables (EVIDENCE, EVIDENCE_FILE,
--   EVIDENCE_KSB, EVIDENCE_REVIEW, IQA_CHECK, WITNESS_CONFIRMATION) have no
--   ISTESTDATA column: their rows for test learners (through
--   ILR.LEARNER.ISTESTDATA) are replaced the same way. Files uploaded to
--   the evidence stage while testing stay in the stage, unlisted.
--   ILR.RECORD_CHANGE: the test rows are emptied, since the changes they
--   describe are undone.
-- It never touches a row with ISTESTDATA = FALSE, organisations, officers,
-- LARS, the flow and job logs (SHARED_DB.OPS), or the shared reference and
-- Companies House tables.
--
-- If a later SQL file adds a column to one of these tables, it must add it
-- to the snapshot table too, or the reset stops and changes nothing.


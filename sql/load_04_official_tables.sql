-- Loading everything, batch 4: the official data sets (plan of 13 October
-- 2026, under decision 15): their RAW tables and grants to DATA_LOAD_ROLE.
--
--   SHARED_DB.RAW (10 tables): English indices of deprivation 2025 (by
--     LSOA, and the local authority summaries); the claimant count and
--     ASHE pay by area (Nomis); ASHE pay by occupation (ONS tables 14 and
--     15, SOC 2020); apprenticeship headlines and the starts and
--     achievements underlying data (by standard, provider and area)
--   OPTIONS_DB.RAW (20 tables): key stage 4 performance; key stage 4 and 16 to 18
--     destination measures; LEO graduate outcomes (national, by subject,
--     and by provider) and further education outcomes (by provider, and
--     earnings)
--
-- RAW tables: columns named exactly as in each file's header, all text, a
-- repeated name numbered; plus SOURCEFILEID and FILEROWNUMBER. Add-only.
-- All text, so suppressed and small numbers stay exactly as published
-- (c, x, z, low, :, .. and the like). Two spreadsheets are converted to
-- rows (ASHE_OCCUPATION, IOD2025_LA_SUMMARY): each cell's text as shown.
-- The loader checks each file's header against its table before loading.
--
-- DATA_LOAD_ROLE gets SELECT and INSERT on every table here: no UPDATE,
-- DELETE, TRUNCATE or CREATE. ILR_APP_ROLE and CRM_APP_ROLE get nothing.
--
-- Paste the whole file into a Snowflake worksheet and Run All, as
-- ACCOUNTADMIN. Safe to run twice.


-- Test journeys, file 2 of 2 (after npm run generate:journeys -- --run):
-- TEST DATA ONLY. Run by hand as ACCOUNTADMIN in a Snowflake worksheet,
-- with Run All, once the full run has finished. Safe to run twice.
--
--   1. Burrow sign-ins for the 15 employer contacts who confirm witness
--      statements (USR-JW01 to USR-JW15). The generator already set their
--      USERID on ILR.EMPLOYER_CONTACT and wrote their confirmations; this
--      makes the sign-ins themselves: an APP_USER at their employer, the
--      EMPLOYER role, and head office (ISHEADOFFICE), so they see all
--      their employer's apprentices. The app can only read ACCESS.
--   2. Backdating the stage moves the flows made: F7 recorded each move in
--      CRM.STAGE_CHANGE (add-only for the app) at the time of the run. Each
--      gets its journey date: moves to Initial assessment the hand-over
--      date (F6, CRM.LEAD.HANDEDOVERAT); moves to Enrolled, Not proceeding
--      and Apprentice placed the date already on the journey
--      (PIPELINE_ITEM.STAGECHANGEDAT, set by the generator). The placements
--      F7 changed get the same date.
--   3. A new snapshot of all the test data, replacing the old one, for
--      sql/test_reset_02_reset.sql: the ILR and employer tables as before,
--      plus ILR.ONBOARDING, ILR.PROGRESS_REVIEW, the Burrow tables, the
--      test sign-ins and roles (ACCESS.APP_USER, USER_ROLE, APP_USER_SITE)
--      and every CRM table. Tables with an ISTESTDATA column are copied by
--      it; PROGRESS_REVIEW and the Burrow tables have none, so they are
--      copied through their test learner.
--   4. Checks.
--
-- The snapshot tables stay in CAPTURE_DB.TEST_BASELINE and
-- CRM_DB.TEST_BASELINE, owned by ACCOUNTADMIN, with no access for the apps.
-- The loaded test files there (ILR_EXPORT_XML, FIS_*, SOURCE_FILE) are not
-- touched.


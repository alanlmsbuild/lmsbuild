-- A. The witness sign-ins. Expected: 15 users, 15 EMPLOYER roles, 15 head
--    office, and CONFIRMATIONS above 0.
SELECT COUNT(*) AS USERS, COUNT_IF(ISHEADOFFICE) AS HEAD_OFFICE,
  (SELECT COUNT(*) FROM SHARED_DB.ACCESS.USER_ROLE WHERE USERID LIKE 'USR-JW%' AND ROLE = 'EMPLOYER' AND REVOKEDAT IS NULL) AS EMPLOYER_ROLES,
  (SELECT COUNT(*) FROM CAPTURE_DB.BURROW.WITNESS_CONFIRMATION WHERE CONFIRMED_BY LIKE 'USR-JW%') AS CONFIRMATIONS
FROM SHARED_DB.ACCESS.APP_USER WHERE USERID LIKE 'USR-JW%';

-- B. The flows' moves by stage, with their dates. Expected: LATEST no later
--    than 2026-10-13 on every row, and EARLIEST well before it (none of
--    them left at the time of the run).
SELECT s.SYSTEMKEY, COUNT(*) AS MOVES, MIN(sc.CHANGEDAT)::DATE AS EARLIEST, MAX(sc.CHANGEDAT)::DATE AS LATEST
FROM CRM_DB.CRM.STAGE_CHANGE sc JOIN CRM_DB.CRM.PIPELINE_STAGE s ON s.STAGEID = sc.TOSTAGEID
WHERE sc.CHANGEDBY = 'flow:F7' AND sc.ORGANISATIONID = 'ORG-T003'
GROUP BY 1 ORDER BY 1;


INSERT INTO SHARED_DB.ACCESS.APP_USER (USERID, ORGANISATIONID, DISPLAYNAME, EMAIL, EMPLOYERID, ISHEADOFFICE, ISTESTDATA, CREATEDBY)
SELECT c.USERID, e.ORGANISATIONID, c.NAME, c.EMAIL, c.EMPLOYERID, TRUE, TRUE, 'journeys_02'
FROM CAPTURE_DB.ILR.EMPLOYER_CONTACT c
JOIN CAPTURE_DB.ILR.EMPLOYER e ON e.EMPLOYERID = c.EMPLOYERID
WHERE c.USERID LIKE 'USR-JW%' AND c.ISTESTDATA = TRUE AND e.ISTESTDATA = TRUE AND e.ORGANISATIONID = 'ORG-T003'
  AND c.USERID NOT IN (SELECT USERID FROM SHARED_DB.ACCESS.APP_USER);

INSERT INTO SHARED_DB.ACCESS.USER_ROLE (ROLEGRANTID, USERID, ROLE, GRANTEDBY, ISTESTDATA)
SELECT 'RG-' || USERID || '-EMPLOYER', USERID, 'EMPLOYER', 'journeys_02', TRUE
FROM SHARED_DB.ACCESS.APP_USER
WHERE USERID LIKE 'USR-JW%' AND ISTESTDATA = TRUE
  AND 'RG-' || USERID || '-EMPLOYER' NOT IN (SELECT ROLEGRANTID FROM SHARED_DB.ACCESS.USER_ROLE);

-- ---------------------------------------------------------------------------
-- 2. The flows' stage moves, at their journey dates
-- ---------------------------------------------------------------------------

UPDATE CRM_DB.CRM.STAGE_CHANGE sc SET CHANGEDAT = l.HANDEDOVERAT
FROM CRM_DB.CRM.PIPELINE_ITEM i, CRM_DB.CRM.LEAD l, CRM_DB.CRM.PIPELINE_STAGE s
WHERE sc.CHANGEDBY = 'flow:F7' AND sc.ORGANISATIONID = 'ORG-T003' AND sc.ISTESTDATA = TRUE
  AND i.ITEMID = sc.ITEMID AND l.LEADID = i.RECORDID AND s.STAGEID = sc.TOSTAGEID
  AND s.SYSTEMKEY = 'ASSESSMENT' AND l.HANDEDOVERAT IS NOT NULL;

UPDATE CRM_DB.CRM.STAGE_CHANGE sc SET CHANGEDAT = i.STAGECHANGEDAT
FROM CRM_DB.CRM.PIPELINE_ITEM i, CRM_DB.CRM.PIPELINE_STAGE s
WHERE sc.CHANGEDBY = 'flow:F7' AND sc.ORGANISATIONID = 'ORG-T003' AND sc.ISTESTDATA = TRUE
  AND i.ITEMID = sc.ITEMID AND i.STAGEID = sc.TOSTAGEID AND s.STAGEID = sc.TOSTAGEID
  AND s.SYSTEMKEY IN ('ENROLLED', 'LOST', 'PLACED');

UPDATE CRM_DB.CRM.PLACEMENT p SET STATUSCHANGEDAT = i.STAGECHANGEDAT
FROM CRM_DB.CRM.PIPELINE_ITEM i
WHERE p.UPDATEDBY = 'flow:F7' AND p.ORGANISATIONID = 'ORG-T003' AND p.ISTESTDATA = TRUE
  AND i.ITEMID = p.CANDIDATEITEMID AND i.CLOSEDAT IS NOT NULL;


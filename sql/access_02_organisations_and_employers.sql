-- Expected: 13 learners and 3 officers, all in ORG-T001, none marked as test data yet.
SELECT 'LEARNER' AS TABLE_NAME, ORGANISATIONID, ISTESTDATA, COUNT(*) AS ROWS_FOUND FROM CAPTURE_DB.ILR.LEARNER GROUP BY 1, 2, 3
UNION ALL
SELECT 'OFFICER', ORGANISATIONID, ISTESTDATA, COUNT(*) FROM CAPTURE_DB.ILR.OFFICER GROUP BY 1, 2, 3
UNION ALL
SELECT 'LEARNING_DELIVERY', NULL, ISTESTDATA, COUNT(*) FROM CAPTURE_DB.ILR.LEARNING_DELIVERY GROUP BY 1, 2, 3;

-- Expected: the 2 existing links (OFF0001 as ASSESSOR for TESTL0002 and TESTL0013), both current.
SELECT LEARNREFNUMBER, OFFICERREFNUMBER, ASSIGNMENTROLE, STARTEDBY, ENDEDAT
FROM CAPTURE_DB.ILR.OFFICER_ASSIGNMENT
ORDER BY LEARNREFNUMBER;


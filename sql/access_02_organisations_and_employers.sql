SHOW GRANTS ON TABLE CAPTURE_DB.ILR.LEARNER_OFFICER;

-- Expected: OWNERSHIP for ACCOUNTADMIN plus INSERT, SELECT and UPDATE for ILR_APP_ROLE on each.
SHOW GRANTS ON TABLE CAPTURE_DB.ILR.OFFICER_ASSIGNMENT;
SHOW GRANTS ON TABLE CAPTURE_DB.ILR.EMPLOYER;

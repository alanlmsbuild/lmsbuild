-- CRM database checks: run these one at a time, as ACCOUNTADMIN, straight
-- after sql/crm_01_database.sql. (npm run check:grants checks the grants
-- too, as both app users.)

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE capture_wh;

-- 1. Who has the new roles. Expected: CRM_APP_ROLE 1 row (USER,
--    CRM_APP_USER); FLOW_OWNER 0 rows (owns procedures, used by no one).
SHOW GRANTS OF ROLE CRM_APP_ROLE ->> SELECT 'CRM_APP_ROLE' AS ROLE, "granted_to", "grantee_name" FROM $1;
SHOW GRANTS OF ROLE FLOW_OWNER ->> SELECT 'FLOW_OWNER' AS ROLE, "granted_to", "grantee_name" FROM $1;

-- 2. The CRM's user. Expected: SERVICE, CRM_APP_ROLE, CRM_WH,
--    has_password false, has_rsa_public_key true; and its key's fingerprint
--    SHA256:RugrXQDI4JaUlYwQZLxItSSvmqbICl2eyvRsYkrWXB8=
SHOW USERS LIKE 'CRM_APP_USER'
  ->> SELECT "name", "type", "default_role", "default_warehouse", "has_password", "has_rsa_public_key", "disabled" FROM $1;
DESC USER CRM_APP_USER ->> SELECT "property", "value" FROM $1 WHERE "property" = 'RSA_PUBLIC_KEY_FP';

-- 3. The two databases can't see each other. Expected: 0 in every column.
SHOW GRANTS TO ROLE CRM_APP_ROLE
  ->> SELECT COUNT_IF(SPLIT_PART("name", '.', 1) = 'CAPTURE_DB') AS CRM_ON_CAPTURE,
             COUNT_IF(SPLIT_PART("name", '.', 1) = 'OPTIONS_DB') AS CRM_ON_OPTIONS,
             COUNT_IF("privilege" IN ('DELETE', 'TRUNCATE', 'OWNERSHIP') OR "privilege" LIKE 'CREATE%') AS CRM_DELETE_OWN_CREATE,
             COUNT_IF(SPLIT_PART("name", '.', 1) = 'SHARED_DB' AND "privilege" NOT IN ('USAGE', 'SELECT')) AS CRM_WRITES_SHARED,
             COUNT_IF("granted_on" = 'ROLE') AS CRM_HOLDS_ROLES
      FROM $1;
SHOW GRANTS TO ROLE ILR_APP_ROLE
  ->> SELECT COUNT_IF(SPLIT_PART("name", '.', 1) = 'CRM_DB') AS ILR_ON_CRM,
             COUNT_IF("granted_on" = 'ROLE' AND "name" IN ('CRM_APP_ROLE', 'FLOW_OWNER')) AS ILR_HOLDS_CRM_ROLES
      FROM $1;

-- 4. Defaults and test data. Expected: PIPELINE 4, PIPELINE_STAGE 30,
--    CLOSE_REASON 18 (two test organisations); FORM_SUBMISSION 12, LEAD 12,
--    LEAD_INTEREST 12, LEAD_CONSENT 24, CONFIRM_TOKEN 12, LEAD_MATCH 7,
--    EMAIL_MESSAGE 13, EMPLOYER 4, EMPLOYER_SITE 4, CONTACT 5,
--    PIPELINE_ITEM 16, STAGE_CHANGE 48, PLACEMENT 3, ACTIVITY 4,
--    ACTIVITY_LINK 10, TASK 4, RECORD_CHANGE 1; NOT_TEST 0 everywhere.
SELECT 'PIPELINE' AS T, COUNT(*) AS N, COUNT_IF(NOT ISTESTDATA) AS NOT_TEST FROM CRM_DB.CRM.PIPELINE
UNION ALL SELECT 'PIPELINE_STAGE', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CRM_DB.CRM.PIPELINE_STAGE
UNION ALL SELECT 'CLOSE_REASON', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CRM_DB.CRM.CLOSE_REASON
UNION ALL SELECT 'FORM_SUBMISSION', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CRM_DB.BRONZE.FORM_SUBMISSION
UNION ALL SELECT 'LEAD', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CRM_DB.CRM.LEAD
UNION ALL SELECT 'LEAD_INTEREST', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CRM_DB.CRM.LEAD_INTEREST
UNION ALL SELECT 'LEAD_CONSENT', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CRM_DB.CRM.LEAD_CONSENT
UNION ALL SELECT 'CONFIRM_TOKEN', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CRM_DB.CRM.CONFIRM_TOKEN
UNION ALL SELECT 'LEAD_MATCH', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CRM_DB.CRM.LEAD_MATCH
UNION ALL SELECT 'EMAIL_MESSAGE', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CRM_DB.CRM.EMAIL_MESSAGE
UNION ALL SELECT 'EMPLOYER', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CRM_DB.CRM.EMPLOYER
UNION ALL SELECT 'EMPLOYER_SITE', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CRM_DB.CRM.EMPLOYER_SITE
UNION ALL SELECT 'CONTACT', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CRM_DB.CRM.CONTACT
UNION ALL SELECT 'PIPELINE_ITEM', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CRM_DB.CRM.PIPELINE_ITEM
UNION ALL SELECT 'STAGE_CHANGE', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CRM_DB.CRM.STAGE_CHANGE
UNION ALL SELECT 'PLACEMENT', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CRM_DB.CRM.PLACEMENT
UNION ALL SELECT 'ACTIVITY', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CRM_DB.CRM.ACTIVITY
UNION ALL SELECT 'ACTIVITY_LINK', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CRM_DB.CRM.ACTIVITY_LINK
UNION ALL SELECT 'TASK', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CRM_DB.CRM.TASK
UNION ALL SELECT 'RECORD_CHANGE', COUNT(*), COUNT_IF(NOT ISTESTDATA) FROM CRM_DB.CRM.RECORD_CHANGE;

-- 5. Every journey's current stage is the last stage it moved to, in its
--    own pipeline, and every stage, reason and owner exists. Expected: 0
--    on every row.
SELECT 'current stage is not the last stage moved to' AS PROBLEM, COUNT(*) AS N
FROM CRM_DB.CRM.PIPELINE_ITEM i
JOIN (SELECT ITEMID, TOSTAGEID FROM CRM_DB.CRM.STAGE_CHANGE QUALIFY ROW_NUMBER() OVER (PARTITION BY ITEMID ORDER BY CHANGEDAT DESC) = 1) c ON c.ITEMID = i.ITEMID
WHERE c.TOSTAGEID <> i.STAGEID
UNION ALL SELECT 'stage in another pipeline, or missing', COUNT(*)
FROM CRM_DB.CRM.PIPELINE_ITEM i LEFT JOIN CRM_DB.CRM.PIPELINE_STAGE s ON s.STAGEID = i.STAGEID
WHERE s.STAGEID IS NULL OR s.PIPELINEID <> i.PIPELINEID
UNION ALL SELECT 'lost journey without a close reason, or with a missing one', COUNT(*)
FROM CRM_DB.CRM.PIPELINE_ITEM i JOIN CRM_DB.CRM.PIPELINE_STAGE s ON s.STAGEID = i.STAGEID
LEFT JOIN CRM_DB.CRM.CLOSE_REASON r ON r.REASONID = i.CLOSEREASONID
WHERE s.CATEGORY = 'lost' AND r.REASONID IS NULL
UNION ALL SELECT 'owner not a user in the same organisation', COUNT(*)
FROM CRM_DB.CRM.PIPELINE_ITEM i LEFT JOIN SHARED_DB.ACCESS.APP_USER u ON u.USERID = i.OWNERUSERID
WHERE i.OWNERUSERID IS NOT NULL AND (u.USERID IS NULL OR u.ORGANISATIONID <> i.ORGANISATIONID)
UNION ALL SELECT 'task owner not a user in the same organisation', COUNT(*)
FROM CRM_DB.CRM.TASK t LEFT JOIN SHARED_DB.ACCESS.APP_USER u ON u.USERID = t.OWNERUSERID
WHERE u.USERID IS NULL OR u.ORGANISATIONID <> t.ORGANISATIONID
UNION ALL SELECT 'test email logged as sent', COUNT(*)
FROM CRM_DB.CRM.EMAIL_MESSAGE WHERE ISTESTDATA AND STATUS = 'sent';

